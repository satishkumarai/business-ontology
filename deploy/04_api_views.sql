-- =============================================================================
-- 04  Consumer API: secure views
--     Views are the read contract. Row access policies on CORE tables are
--     evaluated against the querying role, so each caller sees only what
--     their domain privileges allow.
-- =============================================================================
USE ROLE {{ADMIN_ROLE}};
USE SCHEMA {{DB}}.API;

CREATE OR REPLACE SECURE VIEW V_DOMAIN
  COMMENT = 'Domains the caller can navigate'
AS
SELECT D.DOMAIN_ID, D.PATH AS DOMAIN_PATH, D.NAME, P.PATH AS PARENT_PATH, D.DESCRIPTION,
       D.OWNER_ROLE, D.STEWARD_ROLE, D.CREATED_AT
  FROM {{DB}}.CORE.DOMAIN D
  LEFT JOIN {{DB}}.CORE.DOMAIN P ON P.DOMAIN_ID = D.PARENT_DOMAIN_ID
 WHERE D.IS_ACTIVE;

CREATE OR REPLACE SECURE VIEW V_CONCEPT
  COMMENT = 'Approved, caller-visible concepts (current version only). This is what agents use.'
AS
SELECT C.CONCEPT_ID, C.QUALIFIED_NAME, D.PATH AS DOMAIN_PATH, C.NAME, C.SCOPE, C.KIND,
       V.VERSION_NO, V.DEFINITION, V.SYNONYMS, V.FORMULA, V.EXCLUSIONS, V.FORMULA_PROVENANCE,
       V.SOURCE, V.REVIEWED_BY AS APPROVED_BY, V.REVIEWED_AT AS APPROVED_AT,
       D.OWNER_ROLE, D.STEWARD_ROLE,
       C.PENDING_VERSION_ID IS NOT NULL AS HAS_PENDING_EDIT
  FROM {{DB}}.CORE.CONCEPT C
  JOIN {{DB}}.CORE.CONCEPT_VERSION V ON V.VERSION_ID = C.CURRENT_VERSION_ID AND V.STATUS = 'APPROVED'
  JOIN {{DB}}.CORE.DOMAIN D ON D.DOMAIN_ID = C.DOMAIN_ID AND D.IS_ACTIVE
 WHERE C.STATUS = 'APPROVED';

CREATE OR REPLACE SECURE VIEW V_CONCEPT_HISTORY
  COMMENT = 'Version history the caller may see (approved/superseded; drafts for authors and stewards)'
AS
SELECT C.QUALIFIED_NAME, C.KIND, V.VERSION_ID, V.VERSION_NO, V.STATUS, V.DEFINITION, V.SYNONYMS,
       V.FORMULA, V.EXCLUSIONS, V.FORMULA_PROVENANCE, V.SOURCE, V.SOURCE_REF, V.CHANGE_NOTE,
       V.AUTHOR, V.CREATED_AT, V.REVIEWED_BY, V.REVIEWED_AT, V.REVIEW_NOTE
  FROM {{DB}}.CORE.CONCEPT_VERSION V
  JOIN {{DB}}.CORE.CONCEPT C ON C.CONCEPT_ID = V.CONCEPT_ID;

CREATE OR REPLACE SECURE VIEW V_RELATIONSHIP
  COMMENT = 'Approved edges whose both endpoints are visible to the caller'
AS
SELECT R.REL_ID, S.QUALIFIED_NAME AS SOURCE_QNAME, S.DOMAIN_PATH AS SOURCE_DOMAIN, S.KIND AS SOURCE_KIND,
       R.REL_TYPE, R.CUSTOM_LABEL,
       T.QUALIFIED_NAME AS TARGET_QNAME, T.DOMAIN_PATH AS TARGET_DOMAIN, T.KIND AS TARGET_KIND,
       R.APPROVED_BY, R.APPROVED_AT
  FROM {{DB}}.CORE.RELATIONSHIP R
  JOIN V_CONCEPT S ON S.CONCEPT_ID = R.SOURCE_CONCEPT_ID
  JOIN V_CONCEPT T ON T.CONCEPT_ID = R.TARGET_CONCEPT_ID
 WHERE R.STATUS = 'APPROVED';

CREATE OR REPLACE SECURE VIEW V_REPRESENTATION
  COMMENT = 'Approved links from visible concepts to implementing/describing assets'
AS
SELECT R.REP_ID, C.QUALIFIED_NAME, C.DOMAIN_PATH, R.REP_TYPE, R.ASSET_KIND, R.ASSET_FQN, R.ASSET_MEMBER,
       R.VALIDATION_STATUS, R.LAST_VALIDATED_AT, R.APPROVED_BY, R.APPROVED_AT
  FROM {{DB}}.CORE.REPRESENTATION R
  JOIN V_CONCEPT C ON C.CONCEPT_ID = R.CONCEPT_ID
 WHERE R.STATUS = 'APPROVED';

CREATE OR REPLACE SECURE VIEW V_REVIEW_QUEUE
  COMMENT = 'Pending drafts / edits / links. Stewards see their domains; authors see their own.'
AS
SELECT 'CONCEPT_VERSION' AS ITEM_TYPE, V.VERSION_ID AS ITEM_ID, D.PATH AS DOMAIN_PATH, C.QUALIFIED_NAME AS SUBJECT,
       IFF(V.STATUS = 'DRAFT', 'NEW CONCEPT', 'EDIT v' || V.VERSION_NO) AS CHANGE,
       V.AUTHOR, V.CREATED_AT, V.SOURCE,
       OBJECT_CONSTRUCT('kind', C.KIND, 'definition', V.DEFINITION, 'synonyms', V.SYNONYMS, 'formula', V.FORMULA,
                        'exclusions', V.EXCLUSIONS, 'note', V.CHANGE_NOTE, 'source_ref', V.SOURCE_REF) AS DETAILS
  FROM {{DB}}.CORE.CONCEPT_VERSION V
  JOIN {{DB}}.CORE.CONCEPT C ON C.CONCEPT_ID = V.CONCEPT_ID
  JOIN {{DB}}.CORE.DOMAIN D ON D.DOMAIN_ID = V.DOMAIN_ID
 WHERE V.STATUS IN ('DRAFT', 'PROPOSED')
UNION ALL
SELECT 'RELATIONSHIP', R.REL_ID, D.PATH, S.QUALIFIED_NAME || ' -' || COALESCE(R.CUSTOM_LABEL, R.REL_TYPE) || '-> ' || T.QUALIFIED_NAME,
       'NEW EDGE', R.CREATED_BY, R.CREATED_AT, 'MANUAL',
       OBJECT_CONSTRUCT('note', R.NOTE, 'source_status', S.STATUS, 'target_status', T.STATUS)
  FROM {{DB}}.CORE.RELATIONSHIP R
  JOIN {{DB}}.CORE.CONCEPT S ON S.CONCEPT_ID = R.SOURCE_CONCEPT_ID
  JOIN {{DB}}.CORE.CONCEPT T ON T.CONCEPT_ID = R.TARGET_CONCEPT_ID
  JOIN {{DB}}.CORE.DOMAIN D ON D.DOMAIN_ID = R.DOMAIN_ID
 WHERE R.STATUS = 'DRAFT'
UNION ALL
SELECT 'REPRESENTATION', R.REP_ID, D.PATH, C.QUALIFIED_NAME || ' ' || R.REP_TYPE || ' ' || R.ASSET_FQN || COALESCE('#' || R.ASSET_MEMBER, ''),
       'NEW LINK', R.CREATED_BY, R.CREATED_AT, 'MANUAL',
       OBJECT_CONSTRUCT('note', R.NOTE, 'snapshot', R.LAST_SNAPSHOT, 'concept_status', C.STATUS)
  FROM {{DB}}.CORE.REPRESENTATION R
  JOIN {{DB}}.CORE.CONCEPT C ON C.CONCEPT_ID = R.CONCEPT_ID
  JOIN {{DB}}.CORE.DOMAIN D ON D.DOMAIN_ID = R.DOMAIN_ID
 WHERE R.STATUS = 'DRAFT';

CREATE OR REPLACE SECURE VIEW V_DRIFT_OPEN
  COMMENT = 'Open drift findings (stewards)'
AS
SELECT F.FINDING_ID, C.QUALIFIED_NAME, D.PATH AS DOMAIN_PATH, F.FINDING_TYPE, R.ASSET_KIND, R.ASSET_FQN,
       R.ASSET_MEMBER, F.BASELINE, F.OBSERVED, F.DETECTED_AT
  FROM {{DB}}.CORE.DRIFT_FINDING F
  JOIN {{DB}}.CORE.REPRESENTATION R ON R.REP_ID = F.REP_ID
  JOIN {{DB}}.CORE.CONCEPT C ON C.CONCEPT_ID = F.CONCEPT_ID
  JOIN {{DB}}.CORE.DOMAIN D ON D.DOMAIN_ID = F.DOMAIN_ID
 WHERE F.RESOLVED_AT IS NULL;

CREATE OR REPLACE SECURE VIEW V_AUDIT
  COMMENT = 'Audit trail (stewards see their domains; users see their own actions)'
AS
SELECT A.EVENT_TS, A.ACTOR_USER, A.ACTION, A.ENTITY_TYPE, A.ENTITY_ID, D.PATH AS DOMAIN_PATH, A.DETAILS
  FROM {{DB}}.CORE.AUDIT_EVENT A
  LEFT JOIN {{DB}}.CORE.DOMAIN D ON D.DOMAIN_ID = A.DOMAIN_ID;

CREATE OR REPLACE SECURE VIEW V_AMBIGUOUS_TERMS
  COMMENT = 'Names with more than one approved, caller-visible meaning (agents must disambiguate)'
AS
SELECT LOWER(NAME) AS TERM, COUNT(*) AS MEANINGS, ARRAY_AGG(QUALIFIED_NAME) WITHIN GROUP (ORDER BY QUALIFIED_NAME) AS QUALIFIED_NAMES
  FROM V_CONCEPT
 GROUP BY LOWER(NAME)
HAVING COUNT(*) > 1;
