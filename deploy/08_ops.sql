USE ROLE {{ADMIN_ROLE}};
USE SCHEMA {{DB}}.OPS;

CREATE OR REPLACE TASK T_VALIDATE_REPRESENTATIONS
  WAREHOUSE = {{WAREHOUSE}}
  SCHEDULE = 'USING CRON {{DRIFT_CRON}} UTC'
  USER_TASK_TIMEOUT_MS = 1800000
  SUSPEND_TASK_AFTER_NUM_FAILURES = 3
  COMMENT = 'Re-validate every concept representation; record drift findings for stewards'
AS
  CALL {{DB}}.CORE.VALIDATE_REPRESENTATIONS();

ALTER TASK T_VALIDATE_REPRESENTATIONS RESUME;

CREATE OR REPLACE VIEW V_HEALTH
  COMMENT = 'One-row operational health summary (admin)'
AS
SELECT
  (SELECT COUNT(*) FROM {{DB}}.CORE.DOMAIN WHERE IS_ACTIVE)                                         AS DOMAINS,
  (SELECT COUNT(*) FROM {{DB}}.CORE.CONCEPT WHERE STATUS = 'APPROVED')                             AS APPROVED_CONCEPTS,
  (SELECT COUNT(*) FROM {{DB}}.CORE.CONCEPT WHERE STATUS = 'DRAFT')                                AS DRAFT_CONCEPTS,
  (SELECT COUNT(*) FROM {{DB}}.CORE.CONCEPT_VERSION WHERE STATUS IN ('DRAFT', 'PROPOSED')
      AND CREATED_AT < DATEADD('day', -7, CURRENT_TIMESTAMP()))                                    AS REVIEWS_OLDER_THAN_7D,
  (SELECT COUNT(*) FROM {{DB}}.CORE.DRIFT_FINDING WHERE RESOLVED_AT IS NULL)                       AS OPEN_DRIFT_FINDINGS,
  (SELECT COUNT(*) FROM {{DB}}.CORE.REPRESENTATION WHERE STATUS = 'APPROVED'
      AND (LAST_VALIDATED_AT IS NULL OR LAST_VALIDATED_AT < DATEADD('hour', -48, CURRENT_TIMESTAMP()))) AS STALE_VALIDATIONS,
  (SELECT COUNT(*) FROM {{DB}}.CORE.CONCEPT C WHERE C.STATUS = 'APPROVED' AND C.KIND = 'METRIC'
      AND NOT EXISTS (SELECT 1 FROM {{DB}}.CORE.REPRESENTATION R
                       WHERE R.CONCEPT_ID = C.CONCEPT_ID AND R.STATUS = 'APPROVED' AND R.REP_TYPE = 'IMPLEMENTS')) AS METRICS_WITHOUT_IMPLEMENTATION,
  (SELECT MAX(COMPLETED_TIME) FROM TABLE({{DB}}.INFORMATION_SCHEMA.TASK_HISTORY(
      TASK_NAME => 'T_VALIDATE_REPRESENTATIONS', RESULT_LIMIT => 20)) WHERE STATE = 'SUCCEEDED')    AS LAST_SUCCESSFUL_VALIDATION;

CREATE OR REPLACE VIEW V_STEWARD_WORKLOAD
  COMMENT = 'Pending reviews and open drift per domain (admin)'
AS
SELECT D.PATH AS DOMAIN_PATH, D.STEWARD_ROLE,
       COUNT_IF(V.STATUS IN ('DRAFT', 'PROPOSED'))                                   AS PENDING_VERSIONS,
       MIN(IFF(V.STATUS IN ('DRAFT', 'PROPOSED'), V.CREATED_AT, NULL))               AS OLDEST_PENDING,
       (SELECT COUNT(*) FROM {{DB}}.CORE.DRIFT_FINDING F
         WHERE F.DOMAIN_ID = D.DOMAIN_ID AND F.RESOLVED_AT IS NULL)                  AS OPEN_DRIFT
  FROM {{DB}}.CORE.DOMAIN D
  LEFT JOIN {{DB}}.CORE.CONCEPT_VERSION V ON V.DOMAIN_ID = D.DOMAIN_ID
 WHERE D.IS_ACTIVE
 GROUP BY D.DOMAIN_ID, D.PATH, D.STEWARD_ROLE;
